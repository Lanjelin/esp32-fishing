#!/usr/bin/env python3
"""Download pinned bite references and generate firmware signatures. Requires ffmpeg and C++17.
Raw Blizzard audio is cached under ignored build/, never bundled with the source.
"""
import hashlib
import json
from pathlib import Path
import subprocess
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
CACHE = ROOT / 'build' / 'reference-audio'
CACHE.mkdir(parents=True, exist_ok=True)
SOURCES = json.loads((ROOT / 'tools' / 'bite-reference-sources.json').read_text())
BUILDER = CACHE / 'extract-template'
subprocess.run(['c++', '-std=c++17', '-O2', '-Wall', '-Wextra', '-Werror',
                str(ROOT / 'tools' / 'extract_bite_template.cpp'), '-o', str(BUILDER)], check=True)
references = []
SPEED_FACTORS = (.95, .975, 1., 1.025, 1.05)
PHASE_OFFSETS = tuple(range(0, 960, 160))
for source in SOURCES:
    audio = CACHE / f"{source['id']}.ogg"
    if not audio.exists():
        with urllib.request.urlopen(source['url'], timeout=30) as response:
            audio.write_bytes(response.read())
    data = audio.read_bytes()
    if hashlib.sha256(data).hexdigest() != source['sha256'] or not data.startswith(b'OggS'):
        raise RuntimeError(f"Reference verification failed for {source['id']}")
    pcm = audio.with_suffix('.pcm')
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', str(audio), '-ar', '44100',
                    '-ac', '2', '-f', 's16le', str(pcm)], check=True)
    # Cover bounded playback-speed/pitch variation and analysis-frame phase.
    # Normalize input rate BEFORE asetrate: original assets may be 22050 Hz.
    # Six phases keep the bank within the existing application partition.
    for factor in SPEED_FACTORS:
        variant = pcm
        if factor != 1.:
            variant = CACHE / f"{source['id']}-speed-{factor:g}.pcm"
            subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', str(audio),
                            '-af', f'aresample=44100,asetrate={44100*factor},aresample=44100',
                            '-ac', '2', '-f', 's16le', str(variant)], check=True)
        for padding in PHASE_OFFSETS:
            result = subprocess.run([str(BUILDER), str(variant), str(padding)], check=True, capture_output=True, text=True)
            values = json.loads(result.stdout)
            rows = values['spectrum']
            if len(rows) != 5 or any(len(row) != 16 or not .999 < sum(v*v for v in row) < 1.001 for row in rows):
                raise RuntimeError('Invalid spectral signature')
            if len(values['envelope']) != 5 or not .999 < sum(v*v for v in values['envelope']) < 1.001:
                raise RuntimeError('Invalid envelope signature')
            values['source_id'] = source['id']
            references.append(values)
lines = ['#pragma once', '// Generated by tools/build_bite_templates.py; do not edit.',
         '// Source: https://www.wowhead.com/sound=3355/fishing-hooked',
         '// Classic source: https://www.wowhead.com/classic/sound=3355/fishing-hooked',
         '// Compact normalized features only; original audio remains Blizzard property.',
         '// 5 bounded speed/pitch factors x 6 phases per source; strict gates unchanged.',
         '#include <stdint.h>', '#include \"BiteDetector.h\"',
         f'inline constexpr unsigned biteSourceCount = {len(SOURCES)};',
         'inline constexpr uint32_t biteReferenceIds[] = {' + ', '.join(str(v['source_id']) for v in references) + '};',
         'inline constexpr BiteSignature biteReferences[] = {']
for values in references:
    rows = ['{' + ', '.join(f'{v:.9f}f' for v in row) + '}' for row in values['spectrum']]
    envelope = '{' + ', '.join(f'{v:.9f}f' for v in values['envelope']) + '}'
    lines.append('  {{' + ', '.join(rows) + '}, ' + envelope + '},')
lines += ['};', 'inline constexpr unsigned biteReferenceCount = sizeof(biteReferences) / sizeof(biteReferences[0]);', '']
(ROOT / 'TwoButtonPad' / 'BiteTemplates.h').write_text('\n'.join(lines))
print(f'Generated {len(references)} timing-aligned signatures from {len(SOURCES)} verified sounds; raw audio remains in ignored build cache.')
